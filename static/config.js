// config.js — frontend API base configuration.
//
// S2 (trust separation, see docs/self-hosting.md, "Split Origin (Frontend
// / Signaling Separated)"): the frontend static assets can move to a
// separate static hosting (the static origin), while the backend remains
// ONLY the API/WS on a separate host (a separate API host) — that is, the
// frontend and backend CAN live on different origins, and all fetch/WS
// calls in the frontend must not blindly hit `location.origin`, but a
// configurable base instead.
//
// This file is NOT a build artifact, but a regular static file alongside
// the rest of static/ (loaded by the same `<script src="/static/config.js">`
// as everything else). It is deliberately NOT generated by a build (this
// project has neither webpack nor any build step at all — the whole
// frontend is classic scripts) — the price for that is exactly one file
// that a given deployment may override with its own build (a deployment
// may override this), substituting something like
// `window.API_BASE = 'https://api.example.com';` instead of the line below.
//
// The default (what's in the repository and served by THIS server as-is)
// is same-origin: local development (`cargo run`) and a single-host
// deployment (while the static assets are still served by the same process
// as the API) keep working EXACTLY as before, without a single extra
// setting — the frontend hits the very origin it was loaded from.
//
// `window.API_BASE || ...` (rather than an unconditional assignment) — in
// case a value ever needs to be set even EARLIER (by an inline script in
// the HTML itself, before this file) — this line must not overwrite it.
'use strict';

window.API_BASE = window.API_BASE || location.origin;
