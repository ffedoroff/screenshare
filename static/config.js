// config.js — конфигурация API-базы фронтенда.
//
// Ш2 (разнесение доверия, см. docs/self-hosting.md, «Split Origin (Frontend
// / Signaling Separated)»): статика фронтенда может уехать на отдельный
// статический хостинг (the static origin), а бэкенд остаётся ТОЛЬКО API/WS
// на отдельном хосте (a separate API host) — то есть фронт и бэкенд МОГУТ
// жить на разных origin, и все fetch/WS во фронте должны бить не в
// `location.origin` вслепую, а в настраиваемую базу.
//
// Этот файл — НЕ билд-артефакт, а обычный статический файл рядом с
// остальным static/ (загружается тем же `<script src="/static/config.js">`,
// что и все остальные). Он сознательно генерируется НЕ сборкой (нет ни
// webpack, ни какого-либо build-step у этого проекта вообще — весь фронт
// classic-script'ы) — расплата за это ровно один файл, который конкретный
// деплой может перезаписать своей сборкой (a deployment may override this),
// подставив туда что-то вроде `window.API_BASE = 'https://api.example.com';`
// вместо строки ниже.
//
// Дефолт (то, что лежит в репозитории и раздаётся ЭТИМ сервером как есть) —
// same-origin: локальная разработка (`cargo run`) и однохостовый деплой
// (пока статика ещё раздаётся тем же процессом, что и API) продолжают
// работать ТОЧНО как раньше, без единой лишней настройки — фронт бьёт туда
// же, откуда сам загружен.
//
// `window.API_BASE || ...` (а не безусловное присваивание) — на случай, если
// когда-нибудь понадобится задать значение ещё РАНЬШЕ (инлайн-скриптом в
// самом HTML, до этого файла) — эта строка не должна его затирать.
'use strict';

window.API_BASE = window.API_BASE || location.origin;
