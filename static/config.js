// config.js — конфигурация API-базы фронтенда.
//
// Ш2 (разнесение доверия, см. README.md «Топология Ш2»): статика фронтенда
// уезжает на Cloudflare Pages (домен chat.fedorov.it), а нынешний сервер
// остаётся ТОЛЬКО API/WS на отдельном хосте chat-api.fedorov.it — то есть
// фронт и бэкенд теперь МОГУТ жить на разных origin, и все fetch/WS во
// фронте должны бить не в `location.origin` вслепую, а в настраиваемую базу.
//
// Этот файл — НЕ билд-артефакт, а обычный статический файл рядом с
// остальным static/ (загружается тем же `<script src="/static/config.js">`,
// что и все остальные). Он сознательно генерируется НЕ сборкой (нет ни
// webpack, ни какого-либо build-step у этого проекта вообще — весь фронт
// classic-script'ы) — расплата за это ровно один файл, который CI
// ПЕРЕЗАПИСЫВАЕТ при сборке артефакта под Cloudflare Pages (см.
// .github/workflows/deploy-prod.yml, job `deploy-pages`): туда кладётся
// `window.API_BASE = 'https://chat-api.fedorov.it';` вместо строки ниже.
//
// Дефолт (то, что лежит в репозитории и раздаётся ЭТИМ сервером как есть) —
// same-origin: локальная разработка (`cargo run`) и нынешний прод (пока
// статика ещё раздаётся тем же процессом, что и API, — до переключения DNS
// координатором) продолжают работать ТОЧНО как раньше, без единой лишней
// настройки — фронт бьёт туда же, откуда сам загружен.
//
// `window.API_BASE || ...` (а не безусловное присваивание) — на случай, если
// когда-нибудь понадобится задать значение ещё РАНЬШЕ (инлайн-скриптом в
// самом HTML, до этого файла) — эта строка не должна его затирать.
'use strict';

window.API_BASE = window.API_BASE || location.origin;
